"""``theforge provider init`` scaffold (Cycle 3 Wave M1): writes a minimal,
stdlib-only Forge Protocol v1 provider — manifest template, protocol
skeleton, a conformance test driving :func:`theforge.conformance.check_provider`
and a README with the registration snippet. Nothing is installed globally
and nothing outside the target directory is written; registering the
provider is a manual, deliberate step (a TOML entry in a providers.toml).
"""

