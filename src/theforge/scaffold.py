_PROVIDER_PY = '''\
#!/usr/bin/env python3
"""{id} — Forge Protocol v1 provider skeleton (generated by `theforge provider init`).

stdlib only: reads the Request JSON from stdin, answers a Response envelope on
stdout and always exits 0 — a crash reaches the core as a transport error.
Implement the real work in `op_execute`; keep `manifest.json` truthful.
"""
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

MANIFEST = json.loads(
    Path(__file__).with_name("manifest.json").read_text(encoding="utf-8"))
PRODUCER = {{"id": MANIFEST["id"], "version": MANIFEST["version"]}}
CAPABILITIES = {{c["id"]: c for c in MANIFEST["capabilities"]}}


def _utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _respond(request: dict, *, status: str, payload: dict | None = None,
             error: dict | None = None) -> dict:
    response = {{
        "protocol": "forge/v1",
        "kind": "Response",
        "request_id": request.get("request_id", ""),
        "op": request.get("op"),
        "producer": PRODUCER,
        "status": status,
        "payload": payload or {{}},
        "limitations": [],
        "unknowns": [],
    }}
    if error is not None:
        response["error"] = error
    return response


def op_execute(payload: dict) -> dict:
    """Return an ExecutionResult dict for the requested capability/action.

    The context files are relative to `payload["task"]["workspace_root"]`;
    read only the items listed in `payload["context"]["files"]`, never
    outside the workspace root. Write artifacts under the current working
    directory (the run's work dir) and declare each with its sha256.
    """
    capability = payload["capability"]
    # TODO: real work. This skeleton reports an empty, honest result.
    return {{
        "schema": "theforge/ExecutionResult/v1",
        "producer": PRODUCER,
        "created_at": _utc_now(),
        "status": "ok",
        "findings": [],
        "evidence": [],
        "artifacts": [],
        "limitations": [
            f"{{capability}}: skeleton provider — no work performed yet"],
        "unknowns": [],
    }}


def _handle(request: dict) -> dict:
    op = request.get("op")
    payload = request.get("payload") or {{}}
    if op == "describe":
        return _respond(request, status="ok", payload=MANIFEST)
    if op == "health":
        return _respond(request, status="ok",
                        payload={{"status": "ok", "checks": []}})
    if op == "execute":
        capability = payload.get("capability", "")
        declared = CAPABILITIES.get(capability)
        if declared is None:
            return _respond(request, status="refused", error={{
                "code": "{prefix}-UNKNOWN-CAPABILITY",
                "detail": f"unknown capability {{capability!r}}"}})
        action = payload.get("action", "")
        if action not in declared.get("actions", []):
            return _respond(request, status="refused", error={{
                "code": "{prefix}-UNKNOWN-ACTION",
                "detail": f"unknown action {{action!r}} for {{capability}}"}})
        return _respond(request, status="ok", payload=op_execute(payload))
    return _respond(request, status="refused", error={{
        "code": "{prefix}-UNKNOWN-OP",
        "detail": f"unsupported op {{op!r}}"}})


def main() -> int:
    try:
        request = json.loads(sys.stdin.read())
    except json.JSONDecodeError as exc:
        print(json.dumps(_respond({{"request_id": "", "op": None}},
                                  status="error", error={{
                                      "code": "{prefix}-BAD-REQUEST",
                                      "detail": f"stdin is not a JSON request: {{exc}}"}})))
        return 0
    if request.get("kind") != "Request" or request.get("protocol") != "forge/v1":
        print(json.dumps(_respond(request, status="refused", error={{
            "code": "{prefix}-PROTOCOL",
            "detail": f"unsupported protocol {{request.get('protocol')!r}}"}})))
        return 0
    print(json.dumps(_handle(request)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

